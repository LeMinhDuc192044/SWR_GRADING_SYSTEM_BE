namespace Application.DTOs.Diagrams;

public class DiagramDTO
{
    public Guid DiagramId { get; set; }
    public string Name { get; set; } = string.Empty;
    public string? Description { get; set; }
    public int ElementCount { get; set; }
}

public sealed class DiagramDetailDTO : DiagramDTO
{
    public IReadOnlyList<DiagramElementDTO> Elements { get; set; } = [];
}

public class CreateDiagramRequest
{
    public string Name { get; set; } = string.Empty;
    public string? Description { get; set; }
}

public class UpdateDiagramRequest
{
    public string? Name { get; set; }
    public string? Description { get; set; }
}

public class DiagramElementDTO
{
    public Guid ElementId { get; set; }
    public Guid DiagramId { get; set; }
    public string ElementCode { get; set; } = string.Empty;
    public string Name { get; set; } = string.Empty;
    public string? ShapeType { get; set; }
    public string? Description { get; set; }
    public bool IsRequired { get; set; }
    /// <summary>Template link, or the storage path of the uploaded element image (see <see cref="ImageUrl"/>).</summary>
    public string? FileTemplateUrl { get; set; }
    public Guid? ElementReferenceId { get; set; }
    public string? ElementReferenceName { get; set; }
    public string? ElementReferenceType { get; set; }
    public string? SoftwareType { get; set; }
    /// <summary>Signed URL that streams the uploaded element image, null when none is stored.</summary>
    public string? ImageUrl { get; set; }
}

public class CreateDiagramElementRequest
{
    /// <summary>Diagram the element belongs to.</summary>
    public Guid? DiagramId { get; set; }
    public string ElementCode { get; set; } = string.Empty;
    public string Name { get; set; } = string.Empty;
    public string? ShapeType { get; set; }
    public string? Description { get; set; }
    public bool IsRequired { get; set; }
    // FileTemplateUrl is not accepted here: it is generated by the uploaded image
    // (multipart "image" on create, or POST /api/diagram-elements/{id}/image).
    public Guid? ElementReferenceId { get; set; }
    public string? ElementReferenceType { get; set; }
    public string? SoftwareType { get; set; }
}

public class UpdateDiagramElementRequest
{
    public string? ElementCode { get; set; }
    public string? Name { get; set; }
    public string? ShapeType { get; set; }
    public string? Description { get; set; }
    public bool? IsRequired { get; set; }
    public string? FileTemplateUrl { get; set; }
    public Guid? ElementReferenceId { get; set; }
    public string? ElementReferenceType { get; set; }
    public string? SoftwareType { get; set; }
}

public sealed class AssignDiagramElementRequest
{
    /// <summary>Existing element that should belong to the diagram in the route.</summary>
    public Guid ElementId { get; set; }
}

public sealed class ConnectDiagramElementRequest
{
    public Guid TargetElementId { get; set; }

    /// <summary>Optional label of the connection (stored in element_reference_type).</summary>
    public string? ConnectionType { get; set; }
}

public sealed class DiagramElementImageUpload
{
    public required Stream Content { get; init; }
    public required string FileName { get; init; }
    public string ContentType { get; init; } = "application/octet-stream";
    public long Length { get; init; }
}
